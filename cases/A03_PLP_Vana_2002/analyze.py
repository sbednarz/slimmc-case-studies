# slimmc simulations

run = sl.open("results")
mwd = run.mwd()


# Theoretical PLP positions
kp = 16.0
M_conc = 1124.0 / 158.15
t0 = 2.5
MW = 158.15

L0 = kp * M_conc * t0
M0 = L0 * MW
M1 = 1*M0
M2 = 2*M0
M3 = 3*M0
logM1 = np.log10(M1)
logM2 = np.log10(M2)
logM3 = np.log10(M3)


# %%
plt.figure(figsize=(5, 3))


# Normalize as in Figure 3
y = mwd.y / mwd.y.max()

plt.figure(figsize=(5, 3))

plt.plot(mwd.x, y, "c-", label="slimmc")
plt.plot(x_figs, y_fig3, 'k--', label='Vana 2002')

plt.axvline(
    logM1,
    color="gray",
    linestyle=":",
    linewidth=0.8,
    label="theoretical PLP pos.",
)

for logM in [logM2, logM3]:
    plt.axvline(
        logM,
        color="gray",
        linestyle=":",
        linewidth=0.8,
)

plt.xlabel(r"$\log_{10}(M\ /\ \mathrm{g\,mol^{-1}})$")
plt.ylabel(r"$w_{\log M}$")

plt.xlim(3, 6)
plt.ylim(0, 1.2)

plt.legend(frameon=False)
plt.tight_layout()
plt.savefig("fig3.png", dpi=300)

